const locales: Record<Lang, string> = { cs: 'cs-CZ', en: 'en-GB' }

/** en-GB writes "Sept"; the texts (and the backend) write "Sep". One spelling per screen. */
const enMonth = (s: string) => s.replace(/\bSept\b/, 'Sep')

export function fmtInt(n: number | null | undefined, lang: Lang): string {
  if (n == null || Number.isNaN(n)) return '–'
  return new Intl.NumberFormat(locales[lang]).format(Math.round(n))
}

/** 23 400 -> "23,4 tis." (cs) / "23.4K" (en); below 10 000 the full number. */
export function fmtCompact(n: number | null | undefined, lang: Lang): string {
  if (n == null || Number.isNaN(n)) return '–'
  if (n < 10000) return fmtInt(n, lang)
  const s = new Intl.NumberFormat(locales[lang], { notation: 'compact', maximumFractionDigits: 1 }).format(n)
  return lang === 'cs' ? csTypo(s) : s
}

/** A range of counts with one unit: "5–50 tis.", "od 5 tis.", "do 50 tis." (cs). */
export function fmtRange(min: number | null | undefined, max: number | null | undefined, lang: Lang): string {
  const has = (x: number | null | undefined): x is number => x != null && !Number.isNaN(x)
  const k = (x: number) => new Intl.NumberFormat(locales[lang], { maximumFractionDigits: 1 }).format(x / 1000)
  const kUnit = lang === 'cs' ? ' tis.' : 'K'
  if (has(min) && has(max)) {
    // en: "1K–50K" (a bare "1–50K" reads as "from 1 follower"); cs: "1–50 tis."
    if (min >= 1000 && max >= 1000 && max < 1e6) return lang === 'en' ? `${k(min)}${kUnit}–${k(max)}${kUnit}` : `${k(min)}–${k(max)}${kUnit}`
    return `${fmtCompact(min, lang)}–${fmtCompact(max, lang)}`
  }
  if (has(min)) return lang === 'cs' ? csTypo(`od ${min >= 1000 && min < 1e6 ? `${k(min)}${kUnit}` : fmtInt(min, lang)}`) : `from ${min >= 1000 && min < 1e6 ? `${k(min)}${kUnit}` : fmtInt(min, lang)}`
  if (has(max)) return lang === 'cs' ? csTypo(`do ${max >= 1000 && max < 1e6 ? `${k(max)}${kUnit}` : fmtInt(max, lang)}`) : `up to ${max >= 1000 && max < 1e6 ? `${k(max)}${kUnit}` : fmtInt(max, lang)}`
  return ''
}

