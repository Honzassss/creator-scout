const dicts: Record<Lang, Record<I18nKey, string>> = { cs, en }

/** Plural form: Czech 1 / 2–4 / 5+ (and 0); English 1 / other. Used as {n|one|few|many} in strings.
 *  {many|a|b} picks a for 1 and b otherwise, keyed by a numeric var named "many". */
function pluralForm(lang: Lang, n: number, one: string, few: string, many: string): string {
  if (n === 1) return one
  if (lang === 'cs' && n >= 2 && n <= 4) return few
  return lang === 'cs' ? many : few
}

export function translate(lang: Lang, key: I18nKey, vars?: Record<string, string | number>): string {
  let s: string = dicts[lang][key] ?? dicts.cs[key] ?? key
  if (vars) {
    s = s.replace(/\{(\w+)\|([^|}]*)\|([^|}]*)\|([^|}]*)\}/g, (m, k: string, one: string, few: string, many: string) =>
      k in vars ? pluralForm(lang, Number(String(vars[k]).replace(/\s/g, '').replace(',', '.')), one, few, many) : m,
    )
    s = s.replace(/\{(\w+)\|([^|}]*)\|([^|}]*)\}/g, (m, k: string, one: string, other: string) => (k in vars ? (Number(vars[k]) === 1 ? one : other) : m))
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
  }
  return lang === 'cs' ? csTypo(s) : s
}

/** Pick the right language from a backend {cs, en} dict, falling back sensibly. Czech text gets
 *  Czech typography (non-breaking spaces) at render time. */
export function pick(text: I18nText | string | null | undefined, lang: Lang): string {
  if (text == null) return ''
  const raw = typeof text === 'string' ? text : (text[lang] ?? text.cs ?? text.en ?? text.text ?? Object.values(text)[0] ?? '')
  return lang === 'cs' ? csTypo(raw) : raw
}

export function hasKey(key: string): key is I18nKey {
  return key in cs
}

